import { useRef, type ReactNode, type PointerEvent } from 'react';

/** Touch uses browser scrolling; a mouse may drag the same day strip. */
export function DayTabs({ children }: { children: ReactNode }) {
  const drag = useRef<{ id: number; x: number; left: number; moved: boolean } | null>(null);
  const suppressClick = useRef(false);
  function move(event: PointerEvent<HTMLDivElement>) {
    const current=drag.current;
    if(!current||event.pointerId!==current.id)return;
    const dx=event.clientX-current.x;
    if(!current.moved&&Math.abs(dx)<6)return;
    current.moved=true;suppressClick.current=true;
    if(!event.currentTarget.hasPointerCapture(event.pointerId))event.currentTarget.setPointerCapture(event.pointerId);
    event.preventDefault();event.currentTarget.scrollLeft=current.left-dx;
  }
  function end(event: PointerEvent<HTMLDivElement>) {
    if(drag.current?.id!==event.pointerId)return;
    drag.current=null;
    if(event.currentTarget.hasPointerCapture(event.pointerId))event.currentTarget.releasePointerCapture(event.pointerId);
    // The click generated by this pointer is dispatched before this task.
    setTimeout(()=>{suppressClick.current=false;},0);
  }
  return <div role="region" aria-label="여행 일차 선택" tabIndex={0}
    style={{ flex: 1, minWidth: 0, display: 'flex', alignItems: 'center', gap: 8, paddingRight: 8, overflowX: 'auto', overflowY: 'hidden', touchAction: 'pan-x pinch-zoom', userSelect: 'none', cursor: 'grab' }}
    onPointerDown={event=>{
      if(event.pointerType!=='mouse'||event.button!==0)return;
      suppressClick.current=false;
      drag.current={id:event.pointerId,x:event.clientX,left:event.currentTarget.scrollLeft,moved:false};
    }} onPointerMove={move} onPointerUp={end} onPointerCancel={end}
    onClickCapture={event=>{if(suppressClick.current){event.preventDefault();event.stopPropagation();suppressClick.current=false;}}}
    onKeyDown={event=>{if(event.target!==event.currentTarget)return;if(event.key==='ArrowRight'||event.key==='ArrowLeft'){event.preventDefault();event.currentTarget.scrollLeft+=event.key==='ArrowRight'?100:-100;}}}>
    {children}
  </div>;
}
