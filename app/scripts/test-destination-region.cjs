const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/destination-region.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,context);
const {destinationRegion: resolve, destinationCandidates: candidates, mapDestinationRegion: map} = context.exports;
assert.equal(resolve('경주'),'경상북도 경주시');
assert.equal(resolve('양양'),'강원특별자치도 양양군');
assert.equal(resolve('강서'),undefined);
assert.deepEqual(Array.from(candidates('강서')),['서울특별시 강서구','부산광역시 강서구']);
assert.equal(resolve('서울 강서구'),'서울특별시 강서구');
assert.equal(resolve('경북 경주시'),'경상북도 경주시');
assert.equal(resolve('광주'),undefined);
assert.equal(resolve('광주광역시'),'전남광주통합특별시');
assert.equal(resolve('전남'),'전남광주통합특별시');
assert.equal(resolve('경기도 광주시'),'경기도 광주시');
assert.equal(map('강원도 양양군 양양읍'),'강원특별자치도 양양군');
assert.equal(map('경기 수원시 장안구'),'경기도 수원시');
assert.equal(map('부산광역시 동구 초량동'),'부산광역시');
assert.equal(map('광주광역시 북구'),'전남광주통합특별시');
assert.equal(map('전남 여수시'),'전남광주통합특별시 여수시');
assert.equal(resolve('부산광역시 동구 초량동'),undefined);
console.log('Destination normalization and ambiguous/map choices passed');
