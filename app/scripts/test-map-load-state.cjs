const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const exportsObject={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/map-load-state.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:exportsObject});
const {initialMapLoadState:initial,mapLoadState:reduce}=exportsObject;
const slow=reduce(initial,{type:'timeout',attempt:0});
assert.equal(slow.status,'slow');assert.ok(slow.message);
const late=reduce(slow,{type:'ready',attempt:0});
assert.equal(late.status,'ready');assert.equal(late.message,null);
assert.equal(reduce(late,{type:'timeout',attempt:0}),late,'A queued deadline must not disable a ready map');
const retried=reduce(slow,{type:'retry'});
assert.equal(retried.attempt,1);assert.equal(retried.status,'loading');assert.equal(retried.message,null);
for(const type of ['ready','timeout','error'])assert.equal(reduce(retried,{type,attempt:0}),retried,'Old frames cannot change a retried map');
const failed=reduce(retried,{type:'error',attempt:1,message:'SDK error'});
assert.equal(failed.status,'error');assert.equal(failed.message,'SDK error');
const recovered=reduce(failed,{type:'ready',attempt:1});
assert.equal(recovered.status,'ready');assert.equal(recovered.message,null);
const again=reduce(reduce(failed,{type:'retry'}),{type:'retry'});
assert.equal(again.attempt,3);assert.equal(again.status,'loading');
console.log('Map load checks passed: delayed readiness, deadline race, retry reset, stale-frame rejection, error recovery, repeated retries.');
